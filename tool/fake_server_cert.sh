#!/usr/bin/env bash
# Generates the certificate of the fake Subsonic server used by the tests
# (test/test_helpers/fake_subsonic_server.dart), for localhost, and the CA
# that signs it. Writes:
# - test/test_helpers/fake_server_certificate.dart: certificate, key and CA,
#   so the server can also run inside the app on a device (integration
#   tests), where it can't read files from the repo
# - android/app/src/debug/res/raw/fake_subsonic_server.pem: the CA, trusted
#   for localhost by debug builds only (see
#   android/app/src/debug/res/xml/network_security_config.xml), so ExoPlayer
#   can stream from the server
#
# The server's key is public on purpose: the CA is only trusted for
# localhost, only by debug builds and the tests, and its own key is thrown
# away after signing.
#
# The server's certificate is valid for 825 days, the most macOS accepts for
# a TLS server (Dart verifies through the system there). Run this again
# before it expires; the tests fail with a handshake error once it has.
set -euo pipefail
cd "$(dirname "$0")/.."

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# A CA that signs only the server's certificate; clients trust the CA.
# BoringSSL (Dart) doesn't take a self-signed end-entity certificate as a
# trust anchor.
openssl req -x509 -newkey rsa:2048 -nodes \
  -keyout "$tmp/ca.key" -out "$tmp/ca.pem" -days 7300 \
  -subj "/CN=Voidweaver fake Subsonic server test CA" \
  -addext "basicConstraints=critical,CA:TRUE,pathlen:0" \
  -addext "keyUsage=critical,keyCertSign" 2>/dev/null
openssl req -new -newkey rsa:2048 -nodes \
  -keyout "$tmp/key.pem" -out "$tmp/server.csr" -subj "/CN=localhost" 2>/dev/null
cat > "$tmp/ext.cnf" <<'EXT'
subjectAltName=DNS:localhost,IP:127.0.0.1
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth
EXT
openssl x509 -req -in "$tmp/server.csr" -CA "$tmp/ca.pem" -CAkey "$tmp/ca.key" \
  -CAcreateserial -days 825 -extfile "$tmp/ext.cnf" -out "$tmp/cert.pem" 2>/dev/null
# PKCS#8, which Dart's SecurityContext reads
openssl pkcs8 -topk8 -nocrypt -in "$tmp/key.pem" -out "$tmp/key8.pem"

mkdir -p android/app/src/debug/res/raw
cp "$tmp/ca.pem" android/app/src/debug/res/raw/fake_subsonic_server.pem

{
  echo "// Generated by tool/fake_server_cert.sh. Don't edit."
  echo
  echo "/// Certificate of the fake Subsonic server, for localhost, signed by"
  echo "/// [fakeServerCa]"
  echo "const fakeServerCertificate = '''"
  cat "$tmp/cert.pem"
  echo "''';"
  echo
  echo "/// The CA clients trust for the fake server. It has signed nothing else,"
  echo "/// and its key was thrown away."
  echo "const fakeServerCa = '''"
  cat "$tmp/ca.pem"
  echo "''';"
  echo
  echo "/// Private key of [fakeServerCertificate]. Public on purpose: only debug"
  echo "/// builds trust [fakeServerCa], and only for localhost."
  echo "const fakeServerPrivateKey = '''"
  cat "$tmp/key8.pem"
  echo "''';"
} > test/test_helpers/fake_server_certificate.dart

echo "Wrote android/app/src/debug/res/raw/fake_subsonic_server.pem and test/test_helpers/fake_server_certificate.dart"
